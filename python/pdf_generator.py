"""
Search for Marg bill PDF and generate a fallback invoice when Marg has not exported one.

Marg writes the invoice in two different ways, and they are not equally easy to
identify.

Its WhatsApp message flow drops the PDF into the message queue folder beside a
CSV whose file name carries the bill number, numbering the pair alike —
invoice(5).pdf next to ..._s_vma0453(5).csv. That sidecar names the bill
outright, so it is the first thing looked for.

Its print-screen Export instead writes one fixed name
(C:/Users/Public/MARG/<company>/AA/invoice.pdf) and overwrites it every time,
so the name says nothing about which bill is inside and a stale file from the
previous bill looks identical to a fresh one. Two rules keep the wrong invoice
from going out: nothing written before the current save is accepted while that
save is still in progress, and a fixed-name export must carry the bill number
in its text.
"""

import json
import shutil
import time
import logging
from pathlib import Path

try:
    from fpdf import FPDF
    FPDF_AVAILABLE = True
except ImportError:
    FPDF_AVAILABLE = False

try:
    from pypdf import PdfReader
    PYPDF_AVAILABLE = True
except ImportError:
    PYPDF_AVAILABLE = False

CONFIG_PATH = Path(__file__).parent.parent / "config" / "config.json"

# Our own generated invoices must never be mistaken for a Marg export: they
# land in this folder, and are stamped so older ones are still recognisable.
FALLBACK_DIRNAME = "fallback"
FALLBACK_MARKER = "generated by WhatsApp automation"

# Marg writes a queued invoice and its CSV within a second of each other, and
# that write time is the only thing linking them, so the window stays tight.
PAIR_WRITE_WINDOW_SEC = 5


def _safe_mtime(path):
    """Marg's scratch folders churn constantly; a vanished file must not raise."""
    try:
        return Path(path).stat().st_mtime
    except OSError:
        return 0


# Marg writes the invoice while the hook is already polling, so a file turns up
# mid-write: still locked, or on disk but truncated. Both look like a perfectly
# good candidate by name and timestamp.
_TRAILER_SCAN_BYTES = 2048


def _pdf_ready(path):
    """
    False while Marg still has the file open or unfinished.

    A PDF is only complete once its trailer has been written, so an unreadable
    file and a missing %%EOF both mean "come back on the next poll".
    """
    try:
        size = Path(path).stat().st_size
        with open(path, "rb") as f:
            if size > _TRAILER_SCAN_BYTES:
                f.seek(-_TRAILER_SCAN_BYTES, 2)
            tail = f.read()
    except OSError:
        return False
    return b"%%EOF" in tail


# Reading a PDF is slow and the search polls twice a second, so remember the
# text per file version instead of re-parsing the same invoice hundreds of times.
_TEXT_CACHE = {}


def _pdf_text(path):
    if not PYPDF_AVAILABLE:
        return None
    path = Path(path)
    try:
        stat = path.stat()
    except OSError:
        return None
    key = (str(path).lower(), stat.st_mtime, stat.st_size)
    if key in _TEXT_CACHE:
        return _TEXT_CACHE[key]
    try:
        reader = PdfReader(str(path))
        text = " ".join((page.extract_text() or "") for page in reader.pages[:2])
        producer = str((reader.metadata or {}).get("/Producer", ""))
    except Exception as e:
        logging.debug(f"Cannot read PDF text {path}: {e}")
        text = None
        producer = ""
    if len(_TEXT_CACHE) > 200:
        _TEXT_CACHE.clear()
    _TEXT_CACHE[key] = None if text is None else producer + " " + text
    return _TEXT_CACHE[key]


def _is_ours(path):
    if FALLBACK_DIRNAME in {part.lower() for part in Path(path).parts}:
        return True
    text = _pdf_text(path)
    return bool(text) and FALLBACK_MARKER.lower() in text.lower()


def load_config():
    with open(CONFIG_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


def expand_folder(pattern):
    """Allow glob patterns in configured folders (Marg's company code varies)."""
    pattern = str(pattern)
    if "*" not in pattern and "?" not in pattern:
        return [Path(pattern)]
    p = Path(pattern)
    anchor = Path(p.anchor) if p.anchor else Path(".")
    try:
        rel = p.relative_to(anchor)
    except ValueError:
        return []
    try:
        matches = [m for m in anchor.glob(str(rel)) if m.is_dir()]
    except OSError:
        return []
    return sorted(matches, key=_safe_mtime, reverse=True)


def _pdf_search_folders(cfg):
    marg = cfg.get("marg", {})
    raw = []
    for key in ("bill_export_folder", "pdf_export_folder"):
        p = marg.get(key)
        if p:
            raw.append(p)
    raw.extend(p for p in marg.get("pdf_search_folders", []) if p)

    folders = []
    for pattern in raw:
        folders.extend(expand_folder(pattern))

    seen, out = set(), []
    for folder in folders:
        s = str(folder).lower()
        if s not in seen:
            seen.add(s)
            out.append(folder)
    return out


def _bill_name_variants(bill_no):
    bill_no = str(bill_no or "").strip()
    if not bill_no:
        return []
    variants = {bill_no, bill_no.replace("/", "-"), bill_no.replace("\\", "-")}
    upper = bill_no.upper()
    variants.add(upper)
    variants.add(upper.replace("/", "-"))
    return [v for v in variants if v]


def _candidate_paths(folder, bill_no):
    folder = Path(folder)
    names = _bill_name_variants(bill_no)
    candidates = []
    for name in names:
        candidates.extend([
            folder / f"{name}.pdf",
            folder / f"INV{name}.pdf",
            folder / f"{name}.PDF",
        ])
    # glob partial match inside folder
    if folder.is_dir():
        for name in names:
            for hit in folder.glob(f"*{name}*.pdf"):
                candidates.append(hit)
            for hit in folder.glob(f"*{name}*.PDF"):
                candidates.append(hit)
    return candidates


def _pdf_mentions_bill(path, bill_no):
    """True when bill_no appears in the PDF text. None when it cannot be checked."""
    text = _pdf_text(path)
    if text is None:
        return None
    squashed = "".join(text.upper().split())
    return "".join(str(bill_no).upper().split()) in squashed


def _pdf_matches_amount(path, amount):
    """
    False when the PDF's figures cannot be the bill's total.

    Marg reuses the bill number when a bill is modified, so an archived PDF can
    be an outdated version of the same invoice. The total is what changes, so it
    is the cheapest way to spot a stale copy. None when it cannot be checked.
    """
    if amount in (None, ""):
        return None
    try:
        value = float(str(amount).replace(",", "").strip())
    except ValueError:
        return None
    text = _pdf_text(path)
    if text is None:
        return None
    # Only the 2-decimal form is specific enough: a bare integer matches digits
    # inside licence and HSN numbers printed on the invoice.
    return f"{value:.2f}" in text.replace(",", "")


def _reject(path, bill_no, amount, warned):
    """Log a mismatched PDF once per search instead of on every poll."""
    key = str(path).lower()
    if key not in warned:
        warned.add(key)
        logging.warning(
            f"Ignoring {path.name}: its figures do not include {amount}, "
            f"so it is not the current version of bill {bill_no}"
        )


def _find_paired_pdf(folders, bill_no, since_ts=None, amount=None, warned=()):
    """
    PDF that Marg's WhatsApp flow queued for this bill.

    The queue holds a CSV named after the bill next to the invoice, so the
    sidecar names the bill outright. Their copy numbers look like a pair but
    are not: Marg numbers each file against collisions with its own name, so a
    CSV with a date and bill number of its own stays unsuffixed while the
    fixed invoice.pdf becomes invoice(1).pdf. The write time is the only thing
    that actually links the two, hence the tight window.
    """
    token = str(bill_no or "").strip().lower()
    if not token:
        return None

    best, best_gap, best_mtime = None, None, 0
    for folder in folders:
        if not folder.is_dir():
            continue
        try:
            sidecars = [p for p in folder.glob("*.csv") if token in p.stem.lower()]
            queued = list(folder.glob("invoice*.pdf"))
        except OSError:
            continue
        for sidecar in sidecars:
            sidecar_mtime = _safe_mtime(sidecar)
            if since_ts and sidecar_mtime < since_ts:
                continue
            for pdf in queued:
                mtime = _safe_mtime(pdf)
                if not mtime or _is_ours(pdf):
                    continue
                if since_ts and mtime < since_ts:
                    continue
                gap = abs(mtime - sidecar_mtime)
                if gap > PAIR_WRITE_WINDOW_SEC:
                    continue
                if not _pdf_ready(pdf):
                    logging.debug(f"{pdf.name} is still being written")
                    continue
                if _pdf_matches_amount(pdf, amount) is False:
                    _reject(pdf, bill_no, amount, warned)
                    continue
                # Closest write to the sidecar wins, so a second bill queued
                # moments later cannot claim this one's invoice.
                if best is None or (gap, -mtime) < (best_gap, -best_mtime):
                    best, best_gap, best_mtime = pdf, gap, mtime
    return best


def _find_named_pdf(folders, bill_no, amount=None, warned=(), since_ts=None):
    """
    PDF whose file name carries the bill number, rejected if its total differs.

    since_ts restricts the search to the save in progress. Marg re-exports on
    every save, so without it an archive of an earlier version of the same bill
    is returned instantly and beats the new export that is still being written.
    """
    newest, newest_mtime = None, 0
    bill_upper = str(bill_no).upper()
    for folder in folders:
        paths = list(_candidate_paths(folder, bill_no))
        if folder.is_dir():
            paths.extend(p for p in folder.rglob("*.pdf")
                         if bill_upper in p.stem.upper())
        for path in paths:
            mtime = _safe_mtime(path)
            if not mtime or _is_ours(path):
                continue
            if since_ts and mtime < since_ts:
                continue
            if not _pdf_ready(path):
                logging.debug(f"{path.name} is still being written")
                continue
            if _pdf_matches_amount(path, amount) is False:
                _reject(path, bill_no, amount, warned)
                continue
            if mtime > newest_mtime:
                newest, newest_mtime = path, mtime
    return newest


def _find_fixed_name_pdf(folders, bill_no, since_ts, amount=None, warned=()):
    """
    Marg's Export writes a fixed name (invoice.pdf) and overwrites it, so accept
    it only when it was written after this bill was saved AND its text carries
    the bill number. When the text cannot be read at all, freshness alone
    decides and the risk is logged.
    """
    for folder in folders:
        if not folder.is_dir():
            continue
        for path in sorted(folder.glob("*.pdf"), key=_safe_mtime, reverse=True):
            mtime = _safe_mtime(path)
            if not mtime or mtime < since_ts or _is_ours(path):
                continue
            if not _pdf_ready(path):
                logging.debug(f"{path.name} is still being written")
                continue
            if _pdf_matches_amount(path, amount) is False:
                _reject(path, bill_no, amount, warned)
                continue
            match = _pdf_mentions_bill(path, bill_no)
            if match:
                return path
            if match is None:
                reason = ("pypdf is not installed" if not PYPDF_AVAILABLE
                          else f"{path.name} could not be parsed")
                logging.warning(
                    f"Sending {path.name} for bill {bill_no} on freshness alone — "
                    f"{reason}, so the bill number inside it was never checked"
                )
                return path
            logging.debug(f"{path} is fresh but is not bill {bill_no}")
    return None


def _archive(pdf_path, bill_no, cfg):
    """Copy Marg's export aside before the next export overwrites it."""
    folder = cfg.get("marg", {}).get("bill_export_folder")
    if not folder:
        return pdf_path
    try:
        dest = Path(folder)
        dest.mkdir(parents=True, exist_ok=True)
        dest = dest / f"{str(bill_no).replace('/', '-')}.pdf"
        if dest.resolve() == Path(pdf_path).resolve():
            return pdf_path
        shutil.copy2(pdf_path, dest)
        return dest
    except OSError as e:
        logging.warning(f"Could not archive {pdf_path}: {e}")
        return pdf_path


def get_marg_pdf_path(bill_no, wait_sec=0, since_ts=None, amount=None):
    """
    Find the Marg-exported PDF for bill_no, retrying until wait_sec elapses so
    Marg has time to finish writing it.

    Three ways of sending the wrong invoice are guarded against: since_ts
    rejects a fixed-name export left behind by the previous bill, amount
    rejects a copy made before this bill was modified, and only once the wait
    is over is an older archive of the same bill considered at all.
    """
    cfg = load_config()
    folders = _pdf_search_folders(cfg)
    if since_ts is None:
        since_ts = time.time()
    deadline = time.time() + max(0, float(wait_sec or 0))
    warned = set()

    while True:
        hit = _find_paired_pdf(folders, bill_no, since_ts, amount, warned)
        if hit:
            logging.info(f"Marg PDF found by queue sidecar: {hit}")
            return _archive(hit, bill_no, cfg)

        hit = _find_named_pdf(folders, bill_no, amount, warned, since_ts=since_ts)
        if hit:
            logging.info(f"Marg PDF found by name: {hit}")
            return _archive(hit, bill_no, cfg)

        hit = _find_fixed_name_pdf(folders, bill_no, since_ts, amount, warned)
        if hit:
            logging.info(f"Marg PDF found by content: {hit}")
            return _archive(hit, bill_no, cfg)

        if time.time() >= deadline:
            break
        time.sleep(0.5)

    # Marg wrote nothing for this save. A copy of the same bill from an earlier
    # save is still closer to the truth than a generated summary, and its total
    # has already been checked against this bill's.
    hit = (_find_paired_pdf(folders, bill_no, None, amount, warned)
           or _find_named_pdf(folders, bill_no, amount, warned))
    if hit:
        logging.warning(
            f"No fresh export for bill {bill_no} — sending archived {hit.name} "
            f"from an earlier save of the same bill"
        )
        return _archive(hit, bill_no, cfg)

    logging.warning(f"Marg PDF not found for bill {bill_no} in {[str(f) for f in folders]}")
    return None


def pdf_to_base64(pdf_path):
    import base64
    with open(pdf_path, "rb") as f:
        return base64.b64encode(f.read()).decode("utf-8")


def generate_simple_invoice_pdf(bill_data):
    """Fallback PDF when Marg export folder has no file for this bill."""
    if not FPDF_AVAILABLE:
        raise ImportError("Run: pip install fpdf2")

    cfg = load_config()
    company = cfg["marg"]["company_name"]
    bill_no = bill_data.get("bill_no", "")
    party_name = bill_data.get("party_name", "Customer")
    party_code = bill_data.get("party_code", "")
    amount = bill_data.get("total", bill_data.get("net_amount", "0"))
    bill_date = bill_data.get("bill_date", "")

    pdf = FPDF()
    pdf.set_producer(FALLBACK_MARKER)
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()
    pdf.set_margins(15, 15, 15)

    pdf.set_font("Helvetica", "B", 16)
    pdf.set_fill_color(37, 99, 235)
    pdf.set_text_color(255, 255, 255)
    pdf.cell(0, 12, company, ln=True, fill=True, align="C")
    pdf.set_text_color(0, 0, 0)
    pdf.ln(4)

    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "TAX INVOICE", ln=True, align="C")
    pdf.ln(2)

    pdf.set_font("Helvetica", "", 10)
    rows = [
        ("Bill No", bill_no),
        ("Date", bill_date),
        ("Party", party_name),
        ("Party Code", party_code),
        ("Net Amount", f"Rs. {amount}"),
    ]
    for label, value in rows:
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(40, 7, label + ":", border=0)
        pdf.set_font("Helvetica", "", 10)
        pdf.cell(0, 7, str(value), ln=True, border=0)

    items = bill_data.get("items", [])
    if items:
        pdf.ln(4)
        pdf.set_font("Helvetica", "B", 9)
        col_widths = [70, 25, 30, 30, 25]
        headers = ["Item Name", "Qty", "Rate", "Amount", "GST%"]
        for i, h in enumerate(headers):
            pdf.cell(col_widths[i], 8, h, border=1, align="C")
        pdf.ln()
        pdf.set_font("Helvetica", "", 9)
        for item in items:
            pdf.cell(col_widths[0], 7, str(item.get("name", ""))[:35], border=1)
            pdf.cell(col_widths[1], 7, str(item.get("qty", "")), border=1, align="C")
            pdf.cell(col_widths[2], 7, f"{float(item.get('rate', 0)):,.2f}", border=1, align="R")
            pdf.cell(col_widths[3], 7, f"{float(item.get('amount', 0)):,.2f}", border=1, align="R")
            pdf.cell(col_widths[4], 7, str(item.get("gst", "18")), border=1, align="C")
            pdf.ln()
    else:
        pdf.ln(6)
        pdf.set_font("Helvetica", "I", 9)
        pdf.multi_cell(0, 5, "Note: Marg bill PDF was not found in the export folder. "
                             f"This is a summary invoice {FALLBACK_MARKER}.")

    pdf.ln(6)
    pdf.set_font("Helvetica", "I", 8)
    pdf.cell(0, 5, "Thank you for your business!", align="C", ln=True)

    # Kept out of the search folders so a stale placeholder can never be
    # mistaken for a real Marg export on a later run.
    export_folder = Path(cfg["marg"]["bill_export_folder"]) / FALLBACK_DIRNAME
    export_folder.mkdir(parents=True, exist_ok=True)
    safe_name = str(bill_no).replace("/", "-").replace("\\", "-")
    output_path = export_folder / f"{safe_name}.pdf"
    pdf.output(str(output_path))
    logging.info(f"Generated fallback PDF: {output_path}")
    return output_path
